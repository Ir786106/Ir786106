import { readFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const site = join(root, 'docs');
const read = path => readFileSync(path, 'utf8');
const html = read(join(site, 'index.html'));
const css = read(join(site, 'styles.css'));
const js = read(join(site, 'script.js'));
const readme = read(join(root, 'README.md'));
let passed = 0, failed = 0;
function test(ok, label) {
  console.log(`${ok ? 'PASS' : 'FAIL'} ${label}`);
  if (ok) passed++; else failed++;
}
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(x => x[1]);
const idSet = new Set(ids);
test(ids.length === idSet.size, 'No duplicated HTML IDs');
for (const id of ['top','main','work','about','expertise','journal','contact','nav-links','menu-toggle','page-progress','command-dialog','command-input','copy-email','year']) test(idSet.has(id), `Accessible section / control: ${id}`);
for (const [, path] of html.matchAll(/(?:src|href)="(assets\/[^"#]+)"/g)) test(existsSync(join(site,path)), `Website asset present: ${path}`);
for (const [, path] of readme.matchAll(/(?:src|srcset)="(assets\/profile\/[^"#]+)"/g)) test(existsSync(join(root,path)), `README artwork present: ${path}`);
for (const a of [...html.matchAll(/href="#([^"#]+)"/g)].map(x => x[1])) test(idSet.has(a), `Internal anchor resolves: #${a}`);
test((html.match(/class="project-card project-/g)||[]).length === 4, 'Four custom illustrated project cards');
test((html.match(/class="project-cover"/g)||[]).length === 4, 'Four clickable project covers');
test(html.includes('not verified screenshots'), 'Conceptual visuals are disclosed');
for (const repo of ['food-fight-app','mandi-pro-erp','teamsync-saas','ai-interview-pro']) test(html.includes(`github.com/Ir786106/${repo}`),`Featured repository linked: ${repo}`);
test(html.includes('class="skip-link"'), 'Keyboard skip navigation');
test(html.includes('aria-expanded="false"') && html.includes('aria-controls="nav-links"'), 'Accessible mobile navigation');
test(html.includes('<dialog ') && html.includes('aria-label="Quick navigation"'), 'Accessible keyboard command palette');
test(js.includes("e.ctrlKey || e.metaKey") && js.includes("showModal()"), 'Command palette keyboard interaction');
test(js.includes('navLinks.classList.toggle') && js.includes('closeMenu()'), 'Working responsive menu logic');
test(js.includes('IntersectionObserver'), 'Scroll reveals supported');
test(js.includes('navigator.clipboard.writeText'), 'Copy email interaction');
test(css.includes('prefers-reduced-motion'), 'Reduced motion accessible');
test(css.includes('@media(max-width:350px)') && css.includes('@media(max-width:780px)'), 'Small-screen responsive rules');
test(html.includes('mailto:muhammadirfan.infosec@gmail.com'), 'Contact link provided');
test(readme.includes('<!-- BLOG:START -->') && readme.includes('<!-- BLOG:END -->'), 'Blog auto-refresh markers maintained');
test(existsSync(join(root,'.github/workflows/refresh-profile.yml')), 'Profile update workflow retained');
test(readme.includes('https://ir786106.github.io/Ir786106/'), 'README links to Pages website');
console.log(`\nValidation: ${passed} passed / ${failed} failed`);
if(failed) process.exitCode = 1;
